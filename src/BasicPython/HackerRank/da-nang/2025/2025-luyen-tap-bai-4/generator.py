def create_pattern(n):
    k = random.randrange(0, 10)
    s = [random.choice(string.ascii_uppercase) for _ in range(n)]

    if k >= 5:
        left = [random.choice(string.ascii_uppercase) for _ in range(n//2)]
        right = left[::-1]

        if n % 2 == 0:
            s = left + right
        else:
            s = left + ['?'] + right

    for _ in range(n//4, n):
        p = random.randrange(0, n)
        s[p] = '?'

    return ''.join(s)

def solve(s):
    letters = [x for x in s]
    bd = 0
    kt = len(s) - 1
    ok = True

    while bd <= kt and ok:
        if letters[bd] == '?' and letters[kt] == '?':
            letters[bd] = 'V'
            letters[kt] = 'V'
        elif letters[bd] == '?':
            letters[bd] = letters[kt]
        elif letters[kt] == '?':
            letters[kt] = letters[bd]
        elif letters[bd] != letters[kt]:
            ok = False

        bd += 1
        kt -= 1

    return ''.join(letters) if ok else '-1'

def generate():
    for i in range(len(min_values)):
        n = random.randrange(min_values[i], max_values[i])
        s = create_pattern(n)
        r = solve(s)

        print(f'{n}\n{s}\n{r}')

        fi = open(os.path.join(input_path, f'input{i:02d}.txt'), mode='w')
        fi.write(f'{s}')
        fi.close()

        fo = open(os.path.join(output_path, f'output{i:02d}.txt'), mode='w', encoding='utf-8')
        fo.write(f'{r}')
        fo.close()

